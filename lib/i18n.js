function normalizeLang(value) {
  if (!value) return null;
  const raw = String(value).trim().replace(/_/g, '-');
  if (!raw) return null;
  if (T[raw]) return raw;
  const lower = raw.toLowerCase();
  const found = Object.keys(T).find((key) => key.toLowerCase() === lower);
  if (found) return found;
  const base = lower.split('-')[0];
  if (T[base]) return base;
  // các biến thể tiếng Trung
  if (base === 'zh') return /hant|tw|hk|mo/i.test(raw) ? 'zh-Hant' : 'zh';
  return null;
}

function langForCountry(country, fallback = 'en') {
  if (!country) return fallback;
  const code = String(country).toUpperCase();
  return COUNTRY_LANG[code] || 'en';
}

function t(lang) {
  return T[lang] || T.en;
}

function isRtl(lang) {
  return RTL.has(String(lang).split('-')[0].toLowerCase());
}

function htmlLang(lang) {
  return T[lang] ? lang : 'en';
}

module.exports = { T, COUNTRY_LANG, normalizeLang, langForCountry, t, isRtl, htmlLang };
